_BY_ID = {p.id: p for p in PATTERNS}

SAFETY_RX = re.compile(
    r"\b(с собой что-?(нибудь|то) сдела\w+|незачем жить|не хочу (больше )?жить|покончу с (собой|всем)|"
    r"хочу умереть|убью себя|наложу на себя руки|лучше бы меня не было)\b",
    re.I,
)

GROUPS_THEM = ("manip", "pressure", "aggr", "emotion", "dec")
GROUPS_ME = ("coach",)


def pattern(id_: str) -> PatternDef | None:
    return _BY_ID.get(id_)


def find_hits(text: str, groups: tuple[str, ...] | None = None) -> list[dict]:
    """Ищет признаки в реплике. Возвращает по одному попаданию на паттерн."""
    t = norm(text)
    if not t:
        return []
    hits: list[dict] = []
    for p in PATTERNS:
        if groups and p.group not in groups:
            continue
        count, snippet = 0, ""
        for rx in p.regexes:
            ms = list(rx.finditer(t))
            if ms:
                count += len(ms)
                if not snippet:
                    snippet = ms[0].group(0).strip()
        if count >= p.min_count:
            hits.append({
                "id": p.id, "label": p.label, "emoji": p.emoji, "book": p.book,
                "group": p.group, "weight": p.weight, "count": count,
                "snippet": snippet[:80],
            })
    hits.sort(key=lambda h: -h["weight"])
    return hits


def safety_flag(text: str) -> bool:
    return bool(SAFETY_RX.search(norm(text)))
