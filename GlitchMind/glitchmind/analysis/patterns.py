def norm(text: str) -> str:
    """Нижний регистр, ё→е, схлопнутые пробелы."""
    return re.sub(r"\s+", " ", (text or "").lower().replace("ё", "е")).strip()


@dataclass(frozen=True)
class PatternDef:
    id: str
    label: str
    emoji: str
    book: str          # id книги (откуда приём) или ""
    group: str         # manip | pressure | aggr | emotion | coach | dec
    weight: float
    regexes: tuple
    min_count: int = 1


def P(id_, label, emoji, book, group, weight, *rx, min_count: int = 1) -> PatternDef:
    return PatternDef(id_, label, emoji, book, group, weight,
                      tuple(re.compile(r, re.I) for r in rx), min_count)


